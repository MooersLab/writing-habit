"""The tutorials shown on the Tutorials tab, one HTML page per task.

The pages ship inside the package beside their images, so the tab works with
no network and no documentation checkout. Each page shows the point-and-click
route first and the command line second, because the forms already print the
command they run and the tutorial should teach the same habit.

The images are regenerated by ``scripts/make_tutorial_images.py``, which drives
the real window offscreen, so a screenshot never drifts far from the program.
"""

from __future__ import annotations

from pathlib import Path
from typing import List, Tuple

HERE = Path(__file__).resolve().parent
IMAGES = HERE / "images"

#: (subtab title, page file), in the order of the weekly loop.
PAGES: List[Tuple[str, str]] = [
    ("Start here", "start.html"),
    ("Edit the schedule", "schedule.html"),
    ("Import the plan", "plan.html"),
    ("Import writing effort", "track.html"),
    ("Compare plan and effort", "compare.html"),
    ("Dashboard", "dashboard.html"),
    ("Longer view", "history.html"),
    ("Calendar and sheets", "generate.html"),
    ("Troubleshooting", "troubleshooting.html"),
]


def page_path(name: str) -> Path:
    """Return the path of the page file ``name``."""
    return HERE / name


def page_key(name: str) -> str:
    """The short key a ``tutorial:`` link uses, the file name without ``.html``."""
    return Path(name).stem
